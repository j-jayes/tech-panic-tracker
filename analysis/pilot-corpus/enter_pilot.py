    write("authors", ["author_id", "display_name", "author_type", "orcid_or_viaf", "notes"],
          [list(a) for a in AUTHORS])

    src_header = ["source_id", "title", "container_title", "pub_date", "source_type",
                  "venue_country", "language_original", "is_translation", "url",
                  "archive_url", "doi", "retrieval_track", "search_query_id",
                  "parent_source_id", "duplicates_of", "accessed_date",
                  "full_text_location", "notes"]
    wayback = json.loads((Path(__file__).parent / "wayback.json").read_text())
    src_rows = []
    for (sid, title, container, pub, stype, country, lang, istrans, url, arch, doi,
         track, notes) in SOURCES:
        full_text = ("data/raw/frey-2019-technology-trap.pdf"
                     if sid == "src_freyosborne2013" else "")
        arch = arch or wayback.get(sid, "")
        assert not url or arch, f"{sid}: url set but no archive snapshot"
        src_rows.append([sid, title, container, pub, stype, country, lang, istrans,
                         url, arch, doi, track, "", "", "", "2026-08-26", full_text, notes])
    write("sources", src_header, src_rows)

    pred_rows, pa_rows, pt_rows = [], [], []
    for p in PREDICTIONS:
        row = dict(DEFAULTS)
        techs = p.pop("tech")
        auths = p.pop("authors")
        row.update(p)
        pred_rows.append([row.get(f, "") for f in PRED_FIELDS])
        for aid, role, atype in auths:
            pa_rows.append([row["prediction_id"], aid, role, atype])
        primaries = sum(1 for _, is_p in techs if is_p)
        assert primaries == 1, f"{row['prediction_id']}: {primaries} primary techs"
        for tid, is_p in techs:
            pt_rows.append([row["prediction_id"], tid, str(is_p).lower()])

    write("predictions", PRED_FIELDS, pred_rows)
    write("prediction_authors",
          ["prediction_id", "author_id", "author_role", "author_type_at_prediction"], pa_rows)
    write("prediction_technologies", ["prediction_id", "tech_id", "is_primary"], pt_rows)


